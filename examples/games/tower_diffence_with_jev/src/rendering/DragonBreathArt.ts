export function dragonBreathClips(base: URL): Readonly<Record<BreathDirection | 'effect', string>> {
  return Object.fromEntries([
    ...BREATH_DIRECTIONS.map((direction) => [
      direction,
      new URL(`dragon/emberwing-baby-dragon-breath-${direction}.json`, base).href
    ]),
    ['effect', new URL('effects/dragon-breath-fx.json', base).href]
  ]) as Record<BreathDirection | 'effect', string>
}

export function dragonBreathBodyClips(base: URL): Readonly<Record<string, string>> {
  const urls = dragonBreathClips(base)
  return Object.fromEntries(
    BREATH_DIRECTIONS.map((direction) => [`ai:dragon:attack:${direction}:breath`, urls[direction]])
  )
}
