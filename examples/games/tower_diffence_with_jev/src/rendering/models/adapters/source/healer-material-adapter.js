export function installHealerMaterialAdapter(root, THREE) {
 const normalChunk=THREE?.ShaderChunk?.normal_fragment_maps;
 const scaleLine='mapN.xy *= normalScale;';
 if(typeof normalChunk!=='string' || normalChunk.split(scaleLine).length!==2 || !normalChunk.includes('USE_NORMALMAP_TANGENTSPACE') || !normalChunk.includes('tbn * mapN')) throw new Error('Unsupported Three tangent-normal shader chunk');
 const healerNormalChunk=normalChunk.replace(scaleLine,scaleLine+`
    float healerNormalStrength = max(1.0-healerMask.x,0.0);
    mapN.xy *= healerNormalStrength;
    mapN.z = mix(1.0,mapN.z,clamp(healerNormalStrength,0.0,1.0));`);
 const states=[];
 root.traverse(mesh=>{
  if (!mesh.isMesh) return;
  const attr=mesh.geometry.getAttribute('_blinkrestposition');
  const materials=Array.isArray(mesh.material)?mesh.material:[mesh.material];
  for (const original of materials) {
   if(original.name!=='Healer_Blink_Surface') continue;
   if(!attr) throw new Error('Healer rest-position attribute missing');
   const uniform={value:0};states.push(uniform);
   original.onBeforeCompile=shader=>{
    for(const marker of ['#include <map_fragment>','#include <roughnessmap_fragment>','#include <normal_fragment_maps>']) if(!shader.fragmentShader.includes(marker)) throw new Error('Unsupported Three shader: '+marker);
    shader.uniforms.healerBlink=uniform;
    shader.vertexShader='attribute vec3 _blinkrestposition; varying vec3 healerRestPosition;\n'+shader.vertexShader;
    shader.vertexShader=shader.vertexShader.replace('#include <begin_vertex>','#include <begin_vertex>\nhealerRestPosition = _blinkrestposition;');
    shader.fragmentShader='varying vec3 healerRestPosition; uniform float healerBlink;\n'+healerMasksGLSL+'\n'+shader.fragmentShader;
    shader.fragmentShader=shader.fragmentShader.replace('#include <map_fragment>',`#include <map_fragment>
      vec2 healerMask = healerMasks(healerRestPosition,healerBlink);
      diffuseColor.rgb = mix(diffuseColor.rgb,vec3(0.9900000095367432,0.7400000095367432,0.550000011920929),clamp(healerMask.x,0.0,1.0));
      diffuseColor.rgb = mix(diffuseColor.rgb,vec3(0.00800000038,0.00200000009,0.01400000043),clamp(healerMask.y,0.0,1.0));`);
    shader.fragmentShader=shader.fragmentShader.replace('#include <roughnessmap_fragment>',`#include <roughnessmap_fragment>
      roughnessFactor = roughnessFactor*(1.0-healerMask.x)+0.6800000072*healerMask.x;`);
    // Blender tangent normal strength adjusts XY AND blends Z toward the neutral normal.
    shader.fragmentShader=shader.fragmentShader.replace('#include <normal_fragment_maps>',healerNormalChunk);
   };
   original.customProgramCacheKey=()=> 'healer-source-blink-v2-normal-xyz'; original.needsUpdate=true;
  }
 });
 if(!states.length) throw new Error('Healer material missing');
 return {update(clip,seconds){
   const samples=clip.userData?.blinkAmountSamples;
   if(!samples) throw new Error('Pass animation extras as clip.userData');
   let i=0;while(i+1<samples.length && samples[i+1][0]<=seconds)i++;
   const a=samples[i],b=samples[Math.min(i+1,samples.length-1)];
   const mix=b[0]===a[0]?0:Math.max(0,Math.min(1,(seconds-a[0])/(b[0]-a[0])));
   for(const u of states)u.value=a[1]+(b[1]-a[1])*mix;
 }};
}
