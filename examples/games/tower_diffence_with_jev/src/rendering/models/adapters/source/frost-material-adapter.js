export function installFrostMaterialAdapter(root) {
 const states=[];
 root.traverse(mesh=>{
  if (!mesh.isMesh) return;
  const attr=mesh.geometry.getAttribute('_blinkrestposition');
  const materials=Array.isArray(mesh.material)?mesh.material:[mesh.material];
  for (const original of materials) {
   if(original.name!=='Frost_Blink_Surface') continue;
   if(!attr) throw new Error('Frost rest-position attribute missing');
   const uniform={value:0};states.push(uniform);
   original.onBeforeCompile=shader=>{
    for(const marker of ['#include <map_fragment>','#include <roughnessmap_fragment>','#include <normal_fragment_maps>']) if(!shader.fragmentShader.includes(marker)) throw new Error('Unsupported Three shader: '+marker);
    shader.uniforms.frostBlink=uniform;
    shader.vertexShader='attribute vec3 _blinkrestposition; varying vec3 frostRestPosition;\n'+shader.vertexShader;
    shader.vertexShader=shader.vertexShader.replace('#include <begin_vertex>','#include <begin_vertex>\nfrostRestPosition = _blinkrestposition;');
    shader.fragmentShader='varying vec3 frostRestPosition; uniform float frostBlink;\n'+frostMasksGLSL+'\n'+shader.fragmentShader;
    shader.fragmentShader=shader.fragmentShader.replace('#include <map_fragment>',`#include <map_fragment>
      vec2 frostMask = frostMasks(frostRestPosition,frostBlink);
      diffuseColor.rgb = mix(diffuseColor.rgb,vec3(0.9909999966621399,0.6299999952316284,0.5149999856948853),clamp(frostMask.x,0.0,1.0));
      diffuseColor.rgb = mix(diffuseColor.rgb,vec3(0.00800000038,0.00200000009,0.01400000043),clamp(frostMask.y,0.0,1.0));`);
    shader.fragmentShader=shader.fragmentShader.replace('#include <roughnessmap_fragment>',`#include <roughnessmap_fragment>
      roughnessFactor = roughnessFactor*(1.0-frostMask.x)+0.6800000072*frostMask.x;`);
    // Blender tangent strength scales XY and blends tangent Z toward 1.
    // Requires Three.js vNormalMapUv/tbn tangent-space chunk signatures.
    shader.fragmentShader=shader.fragmentShader.replace('#include <normal_fragment_maps>',`#if defined(USE_NORMALMAP_TANGENTSPACE)
      vec3 frostMapN = texture2D(normalMap, vNormalMapUv).xyz * 2.0 - 1.0;
      float frostNormalStrength = 1.0 - frostMask.x;
      frostMapN.xy *= normalScale * frostNormalStrength;
      frostMapN.z = mix(1.0, frostMapN.z, clamp(frostNormalStrength, 0.0, 1.0));
      normal = normalize(tbn * frostMapN);
      #else
      #include <normal_fragment_maps>
      #endif`);
   };
   original.customProgramCacheKey=()=> 'frost-source-blink-v2'; original.needsUpdate=true;
  }
 });
 if(!states.length) throw new Error('Frost material missing');
 return {update(clip,seconds){
   const samples=clip.userData?.blinkAmountSamples;
   if(!samples) throw new Error('Pass animation extras as clip.userData');
   let i=0;while(i+1<samples.length && samples[i+1][0]<=seconds)i++;
   const a=samples[i],b=samples[Math.min(i+1,samples.length-1)];
   const mix=b[0]===a[0]?0:Math.max(0,Math.min(1,(seconds-a[0])/(b[0]-a[0])));
   for(const u of states)u.value=a[1]+(b[1]-a[1])*mix;
 }};
}
