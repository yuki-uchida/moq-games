export function installWraithMaterialAdapter(root, THREE) {
 const normalChunk=THREE?.ShaderChunk?.normal_fragment_maps;
 const scaleLine='mapN.xy *= normalScale;';
 if(typeof normalChunk!=='string' || normalChunk.split(scaleLine).length!==2 || !normalChunk.includes('USE_NORMALMAP_TANGENTSPACE') || !normalChunk.includes('tbn * mapN')) throw new Error('Unsupported Three tangent-normal shader chunk');
 const wraithNormalChunk=normalChunk.replace(scaleLine,scaleLine+`
    float wraithNormalStrength = max(1.0-wraithMask.x,0.0);
    mapN.xy *= wraithNormalStrength;
    mapN.z = mix(1.0,mapN.z,clamp(wraithNormalStrength,0.0,1.0));`);
 const states=[];
 root.traverse(mesh=>{
  if (!mesh.isMesh) return;
  const attr=mesh.geometry.getAttribute('_blinkrestposition');
  const materials=Array.isArray(mesh.material)?mesh.material:[mesh.material];
  for (const original of materials) {
   if(original.name!=='Wraith_Blink_Surface') continue;
   if(!attr) throw new Error('Wraith rest-position attribute missing');
   const uniform={value:0};states.push(uniform);
   original.onBeforeCompile=shader=>{
    for(const marker of ['#include <map_fragment>','#include <roughnessmap_fragment>','#include <normal_fragment_maps>']) if(!shader.fragmentShader.includes(marker)) throw new Error('Unsupported Three shader: '+marker);
    shader.uniforms.wraithBlink=uniform;
    shader.vertexShader='attribute vec3 _blinkrestposition; varying vec3 wraithRestPosition;\n'+shader.vertexShader;
    shader.vertexShader=shader.vertexShader.replace('#include <begin_vertex>','#include <begin_vertex>\nwraithRestPosition = _blinkrestposition;');
    shader.fragmentShader='varying vec3 wraithRestPosition; uniform float wraithBlink;\n'+wraithMasksGLSL+'\n'+shader.fragmentShader;
    shader.fragmentShader=shader.fragmentShader.replace('#include <map_fragment>',`#include <map_fragment>
      vec2 wraithMask = wraithMasks(wraithRestPosition,wraithBlink);
      diffuseColor.rgb = mix(diffuseColor.rgb,vec3(0.9800000190734863,0.5379999876022339,0.367000013589859),clamp(wraithMask.x,0.0,1.0));
      diffuseColor.rgb = mix(diffuseColor.rgb,vec3(0.02500000037252903,0.017999999225139618,0.008999999612569809),clamp(wraithMask.y,0.0,1.0));`);
    shader.fragmentShader=shader.fragmentShader.replace('#include <roughnessmap_fragment>',`#include <roughnessmap_fragment>
      roughnessFactor = roughnessFactor*(1.0-wraithMask.x)+0.6800000072*wraithMask.x;`);
    // Blender tangent normal strength adjusts XY AND blends Z toward the neutral normal.
    shader.fragmentShader=shader.fragmentShader.replace('#include <normal_fragment_maps>',wraithNormalChunk);
   };
   original.customProgramCacheKey=()=> 'wraith-source-blink-v2-normal-xyz'; original.needsUpdate=true;
  }
 });
 if(!states.length) throw new Error('Wraith material missing');
 return {update(clip,seconds){
   const samples=clip.userData?.blinkAmountSamples;
   if(!samples) throw new Error('Pass animation extras as clip.userData');
   let i=0;while(i+1<samples.length && samples[i+1][0]<=seconds)i++;
   const a=samples[i],b=samples[Math.min(i+1,samples.length-1)];
   const mix=b[0]===a[0]?0:Math.max(0,Math.min(1,(seconds-a[0])/(b[0]-a[0])));
   for(const u of states)u.value=a[1]+(b[1]-a[1])*mix;
 }};
}
