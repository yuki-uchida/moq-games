import { createHash } from 'node:crypto'
import { expect, test, vi } from 'vitest'
import { careerSheetFrames, careerSheets } from '../src/art/careers'
import { prewarmAppearanceFrame, retainAppearancePrewarm, sheet } from '../src/art/index'

test('all 48 outfits retain baseline pixels, frame order and animation timing', () => {
  const hash = createHash('sha256')
  expect(Object.keys(careerSheets)).toHaveLength(48)
  for (const [key, factory] of Object.entries(careerSheets)) {
    const [, body, career] = key.split(':')
    const frames = careerSheetFrames(body, career)
    const expected = factory()
    const count = Object.values(expected).reduce((total, anim) => total + anim.frames.length, 0)
    for (let index = 0; index < count; index++) expect(frames.next().done).toBe(false)
    const result = frames.next()
    expect(result.done).toBe(true)
    expect(result.value).toEqual(expected)
    hash.update(key)
    for (const [name, anim] of Object.entries(expected)) {
      hash.update(JSON.stringify([name, anim.fps, anim.loop, anim.hold ?? null]))
      for (const frame of anim.frames) hash.update(frame.data)
    }
  }
  expect(hash.digest('hex')).toBe('d4e26d373b550d264db2e63ef05784bcc4cfe41607a7ee74b402419d619cda1a')
}, 15_000)

test('partial work is bounded, discarded on invalidation or expiry, and synchronous drawing wins', () => {
  const first = 'player:junior:soccer'
  const second = 'player:high:social'
  const count = Object.values(careerSheets[first]()).reduce((total, anim) => total + anim.frames.length, 0)
  expect(prewarmAppearanceFrame(first)).toBe(false)
  expect(prewarmAppearanceFrame(second)).toBe(false)
  for (let index = 0; index < count; index++) expect(prewarmAppearanceFrame(first)).toBe(false)
  retainAppearancePrewarm([])
  for (let index = 0; index < count; index++) expect(prewarmAppearanceFrame(first)).toBe(false)
  const clock = vi.spyOn(performance, 'now').mockReturnValue(performance.now() + 251)
  for (let index = 0; index < count; index++) expect(prewarmAppearanceFrame(first)).toBe(false)
  clock.mockRestore()
  const visible = sheet(first)
  expect(prewarmAppearanceFrame(first)).toBe(true)
  expect(sheet(first)).toBe(visible)
  retainAppearancePrewarm([])
})

test('unclothed base sheets are not synchronously generated by idle prewarming', () => {
  expect(prewarmAppearanceFrame('player:junior')).toBe(true)
})

test('completed prewarm publishes to the same synchronous cache', () => {
  const id = 'player:elder:creative'
  const expected = careerSheets[id]()
  const count = Object.values(expected).reduce((total, anim) => total + anim.frames.length, 0)
  for (let index = 0; index < count; index++) expect(prewarmAppearanceFrame(id)).toBe(false)
  expect(prewarmAppearanceFrame(id)).toBe(true)
  const warmed = sheet(id)
  expect(warmed).toEqual(expected)
  expect(sheet(id)).toBe(warmed)
})
