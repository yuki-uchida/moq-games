/** Tiny DOM helpers (no framework): element builder, cached text/style setters for per-frame HUD updates. */

export type Child = Node | string | number | null | undefined | false | readonly Child[]

export interface Props {
  class?: string
  text?: string
  html?: string
  attrs?: Record<string, string | number | boolean | undefined>
  style?: Partial<Record<string, string>>
  dataset?: Record<string, string>
  on?: Partial<{ [K in keyof HTMLElementEventMap]: (e: HTMLElementEventMap[K]) => void }>
}

function append(el: Element, child: Child): void {
  if (child == null || child === false) return
  if (Array.isArray(child)) {
    for (const c of child as readonly Child[]) append(el, c)
    return
  }
  el.append(child instanceof Node ? child : String(child))
}

export function h<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  props?: Props | string | null,
  ...children: Child[]
): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag)
  if (typeof props === 'string') el.className = props
  else if (props) {
    if (props.class) el.className = props.class
    if (props.text != null) el.textContent = props.text
    if (props.html != null) el.innerHTML = props.html
    if (props.attrs) {
      for (const [k, v] of Object.entries(props.attrs)) {
        if (v === undefined || v === false) continue
        el.setAttribute(k, v === true ? '' : String(v))
      }
    }
    if (props.style) for (const [k, v] of Object.entries(props.style)) if (v != null) el.style.setProperty(k, v)
    if (props.dataset) Object.assign(el.dataset, props.dataset)
    if (props.on) {
      for (const [k, fn] of Object.entries(props.on)) if (fn) el.addEventListener(k, fn as EventListener)
    }
  }
  for (const c of children) append(el, c)
  return el
}

const SVG_NS = 'http://www.w3.org/2000/svg'

/** Parses an SVG string (trusted, generated by our code) into an element. */
export function svg(markup: string, className?: string): SVGSVGElement {
  const tpl = document.createElement('template')
  tpl.innerHTML = markup.trim()
  const el = tpl.content.firstElementChild as SVGSVGElement
  if (className) el.setAttribute('class', className)
  return el
}

export const svgEl = <K extends keyof SVGElementTagNameMap>(tag: K, attrs: Record<string, string | number> = {}) => {
  const el = document.createElementNS(SVG_NS, tag)
  for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, String(v))
  return el
}

/** Sets textContent only when it changed (no layout work for unchanged HUD values). */
export function setText(el: Element, value: string): void {
  const cache = el as Element & { __t?: string }
  if (cache.__t === value) return
  cache.__t = value
  el.textContent = value
}

/** Sets a style property only when it changed. */
export function setStyle(el: HTMLElement | SVGElement, prop: string, value: string): void {
  const cache = el as (HTMLElement | SVGElement) & { __s?: Record<string, string> }
  const map = (cache.__s ??= {})
  if (map[prop] === value) return
  map[prop] = value
  el.style.setProperty(prop, value)
}

export function setClass(el: Element, name: string, on: boolean): void {
  if (el.classList.contains(name) !== on) el.classList.toggle(name, on)
}

export function setAttr(el: Element, name: string, value: string): void {
  if (el.getAttribute(name) !== value) el.setAttribute(name, value)
}

export const hex = (n: number) => `#${n.toString(16).padStart(6, '0')}`

/** Drops empty entries so the list can go to append/replaceChildren. */
export const nodes = (...list: (Node | string | null | undefined | false)[]): (Node | string)[] =>
  list.filter((n): n is Node | string => n != null && n !== false)

export function clear(el: Element): void {
  while (el.firstChild) el.removeChild(el.firstChild)
}

/** True when the user asked for less motion (setting or OS). */
export const reducedMotion = () => document.documentElement.classList.contains('reduced-motion')
